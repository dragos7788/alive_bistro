/**
 * Generates seed SQL from src/features/menu/menu-data.json.
 * Usage: node scripts/seed-menu-db.mjs
 * Then: wrangler d1 execute alive-bistro-menu --local --file=scripts/seed-data.sql
 */

import { readFileSync, writeFileSync } from "fs"
import { fileURLToPath } from "url"
import { join, dirname } from "path"

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const menuPath = join(scriptDirectory, "..", "src", "features", "menu", "menu-data.json")
const menuData = JSON.parse(readFileSync(menuPath, "utf-8"))

function q(value) {
  if (value == null) return "NULL"
  return `'${String(value).replace(/'/g, "''")}'`
}

function slugify(name) {
  return name
    .toLowerCase()
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60)
}

const lines = [
  "-- Generated by scripts/seed-menu-db.mjs — do not edit manually",
  "-- Replaces the existing menu with src/features/menu/menu-data.json.",
  "DELETE FROM items;",
  "DELETE FROM categories;",
  "",
]

for (const group of menuData) {
  let categoryOrder = 0
  for (const category of group.categories) {
    lines.push(
      `INSERT OR REPLACE INTO categories (id, group_id, label, icon_key, sort_order) VALUES (${q(category.id)}, ${q(group.id)}, ${q(category.label)}, ${q(category.iconKey)}, ${categoryOrder++});`,
    )
    let itemOrder = 0
    for (const item of category.items) {
      const id = `${category.id}--${slugify(item.name)}`
      lines.push(
        `INSERT OR REPLACE INTO items (id, category_id, name, description, price, image_url, tag, calories, protein, carbs, fat, sort_order, menu_component) VALUES (${q(id)}, ${q(category.id)}, ${q(item.name)}, ${q(item.description)}, ${q(item.price)}, NULL, ${q(item.tag)}, ${q(item.macros?.calories)}, ${q(item.macros?.protein)}, ${q(item.macros?.carbs)}, ${q(item.macros?.fat)}, ${itemOrder++}, ${item.menuComponent ? 1 : 0});`,
      )
    }
  }
}

const outputPath = join(scriptDirectory, "seed-data.sql")
writeFileSync(outputPath, lines.join("\n") + "\n")
const totalItems = menuData.flatMap((group) => group.categories).flatMap((category) => category.items).length
const totalCategories = menuData.reduce((count, group) => count + group.categories.length, 0)
console.log(`Wrote ${totalItems + totalCategories} INSERT statements to scripts/seed-data.sql`)
console.log(`Expected: SELECT count(*) FROM items = ${totalItems}`)
